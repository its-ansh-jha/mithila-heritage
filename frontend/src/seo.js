function setKeywords(keys){
 return [...new Set(keys.flatMap(key=>seoKeywordClusters[key]||[]))].join(', ');
}

export function getSeo(pathname,site){
 const clean=pathname.replace(/\/$/,'')||'/';
 if(clean.startsWith('/rooms/')){
  const id=clean.split('/')[2];
  const room=site?.rooms?.find(r=>r.id===id);
  const seo=roomSeo(room);
  return {...seo,canonical:SITE_URL+clean,keywords:setKeywords(seo.keywords),type:'product',room};
 }
 const seo=routeSeo[clean]||{
  title:'Mithila Heritage | Hotel in Patna',
  description:'Mithila Heritage is a boutique hotel in Patna with rooms, rooftop dining and banquet spaces.',
  image:'/images/IMG_3446.webp',
  keywords:['hotel','brand']
 };
 return {...seo,canonical:SITE_URL+clean,keywords:setKeywords(seo.keywords),type:'website'};
}

